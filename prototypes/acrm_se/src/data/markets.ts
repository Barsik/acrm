// Фактический доход YTD по рынку: доля комиссии клиента, пропорциональная
// числу его продуктов в этом рынке, за YTD_MONTHS месяцев.
export function blFact(bl: BusinessLine): number {
  const blClients = clients.filter(c => c.products.some(p => bl.products.includes(p)));
  return blClients.reduce((s, c) => {
    const k = c.products.filter(p => bl.products.includes(p)).length;
    return s + c.commMTD * YTD_MONTHS * (k / c.products.length);
  }, 0);
}

// Помесячный доход по рынку (млн ₽), разложенный из годового по весам.
export function blMonthlyRevenue(bl: BusinessLine): number[] {
  const annual = YEAR_PCT > 0 ? blFact(bl) / YEAR_PCT : 0;
  const mult = BL_MULT_12[bl.name] || Array(12).fill(1);
  const mSum = mult.reduce((s, v) => s + v, 0);
  return mult.map(m => (mSum > 0 ? (annual * m) / mSum / 1e6 : 0));
}


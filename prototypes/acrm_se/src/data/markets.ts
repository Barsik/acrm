export function fmtMoney(n: number): string {
  if (n >= 1e12) return `${formatNumber(n / 1e12)} трлн ₽`;
  if (n >= 1e9) return `${formatNumber(n / 1e9)} млрд ₽`;
  if (n >= 1e6) return `${formatNumber(n / 1e6)} млн ₽`;
  if (n >= 1e3) return `${formatNumber(n / 1e3)} тыс ₽`;
  return `${formatNumber(n)} ₽`;
}
export const fmtMln = (n: number): string => `${formatNumber(n / 1e6)} млн ₽`;

// Разделитель тысяч пробелами.
export const fmtThousands = (n: number): string =>
  Math.round(n).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ');

// Линейная регрессия по ряду → знак тренда и нормализованный наклон.
export function trendInfo(values: number[]): { arrow: string; color: string } {
  const nv = values.length;
  const sumX = (nv * (nv - 1)) / 2;
  const sumX2 = (nv * (nv - 1) * (2 * nv - 1)) / 6;
  const sumY = values.reduce((s, v) => s + v, 0);
  const sumXY = values.reduce((s, v, i) => s + i * v, 0);
  const denom = nv * sumX2 - sumX * sumX;
  const slope = denom ? (nv * sumXY - sumX * sumY) / denom : 0;
  const relSlope = sumY ? (slope / (sumY / nv)) * 100 : 0;
  const color = relSlope > 0.5 ? '#187A40' : relSlope < -0.5 ? '#C43A3A' : '#ADADAD';
  const arrow = relSlope > 0.5 ? '↑' : relSlope < -0.5 ? '↓' : '→';
  return { arrow, color };
}
